def infer_region(s):
    name = s.get("name", "")
    sid = s.get("id", "")
    district = s.get("district", "")

    # 1. ID / name 精确映射（最优先）
    if sid in ID_TO_REGION:
        return ID_TO_REGION[sid]
    if name in ID_TO_REGION:
        return ID_TO_REGION[name]

    # 2. 关键词规则
    for region, keywords in KEYWORD_RULES:
        for kw in keywords:
            if kw in name:
                return region

    # 3. 按数据区县兜底
    if district == "chengliuqu":
        return "城六区"
    return DISTRICT_LABELS.get(district, district)

def main():
    schools = json.loads(SCHOOLS_PATH.read_text(encoding="utf-8"))
    unmatched = []
    for s in schools:
        region = infer_region(s)
        s["region"] = region
        sid = s.get("id", "")
        name = s.get("name", "")
        if sid not in ID_TO_REGION and name not in ID_TO_REGION and not any(kw in name for _, kws in KEYWORD_RULES for kw in kws):
            unmatched.append(f"{sid}\t{name}\t{s.get('district')}")

    SCHOOLS_PATH.write_text(json.dumps(schools, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Updated {len(schools)} schools. region field added.")
    if unmatched:
        print(f"\nUnmatched ({len(unmatched)}):")
        print("\n".join(unmatched))
    else:
        print("\nAll schools matched.")

if __name__ == "__main__":
    main()
